CREATE TABLE quest_skill_requirements (
    quest_id UUID NOT NULL REFERENCES quests(id) ON DELETE CASCADE,
    skill_code VARCHAR(100) NOT NULL,
    PRIMARY KEY (quest_id, skill_code)
);

CREATE INDEX idx_quest_skill_requirements_skill
    ON quest_skill_requirements(skill_code);

