-- 사용자가 퀘스트를 시작한 뒤 완료하거나 중단할 때까지의 수행 단위
CREATE TABLE quest_sessions
(
    id UUID PRIMARY KEY,
    member_id UUID NOT NULL,
    quest_id UUID NOT NULL,
    quest_difficulty VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_steps INTEGER NOT NULL,
    completed_steps INTEGER NOT NULL DEFAULT 0,
    reward_points INTEGER NOT NULL DEFAULT 0,
    started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    abandoned_at TIMESTAMP(6) WITH TIME ZONE,
    abandon_reason VARCHAR(50),

    CONSTRAINT fk_quest_session_member
        FOREIGN KEY (member_id) REFERENCES member (id) ON DELETE RESTRICT,
    CONSTRAINT fk_quest_session_quest
        FOREIGN KEY (quest_id) REFERENCES quests (id) ON DELETE RESTRICT,
    CONSTRAINT chk_quest_session_status
        CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'ABANDONED')),
    CONSTRAINT chk_quest_session_difficulty
        CHECK (quest_difficulty IN ('VERY_EASY', 'EASY', 'NORMAL', 'HARD', 'VERY_HARD')),
    CONSTRAINT chk_quest_session_step_counts
        CHECK (total_steps >= 1 AND completed_steps >= 0 AND completed_steps <= total_steps),
    CONSTRAINT chk_quest_session_reward
        CHECK (reward_points >= 0)
);

-- 단계별 선택을 수정하지 않는 원본 이벤트로 저장한다.
CREATE TABLE quest_events
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL,
    step_id UUID NOT NULL,
    choice_id UUID NOT NULL,
    attempt_number INTEGER NOT NULL,
    correct BOOLEAN NOT NULL,
    hint_used BOOLEAN NOT NULL,
    response_time_ms BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_quest_event_session
        FOREIGN KEY (session_id) REFERENCES quest_sessions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_quest_event_step
        FOREIGN KEY (step_id) REFERENCES quest_steps (id) ON DELETE RESTRICT,
    CONSTRAINT fk_quest_event_choice
        FOREIGN KEY (choice_id) REFERENCES quest_choices (id) ON DELETE RESTRICT,
    CONSTRAINT uq_quest_event_attempt
        UNIQUE (session_id, step_id, attempt_number),
    CONSTRAINT chk_quest_event_attempt
        CHECK (attempt_number >= 1),
    CONSTRAINT chk_quest_event_response_time
        CHECK (response_time_ms >= 0)
);

CREATE INDEX idx_quest_sessions_member_started
    ON quest_sessions (member_id, started_at DESC);

CREATE INDEX idx_quest_sessions_member_quest_completed
    ON quest_sessions (member_id, quest_id, completed_at DESC);

CREATE INDEX idx_quest_events_session_created
    ON quest_events (session_id, created_at);
