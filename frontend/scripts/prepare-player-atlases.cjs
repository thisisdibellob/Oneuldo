/* Lossless packaging of existing player frames. No drawing, filtering, resizing or frame removal. */
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');

const root = path.resolve(__dirname, '..');
const input = path.join(root, 'assets/images/game/characters/player/chibi-user-v3');
const sprintInput = path.join(root, 'assets/images/game/characters/player/chibi-sprint2-v1');
const sprintProvenance = JSON.parse(fs.readFileSync(path.join(sprintInput, 'provenance.json'), 'utf8'));
const output = path.join(root, 'assets/images/game/characters/player/chibi-atlas-v1');
const directions = ['front', 'frontLeft', 'left', 'backLeft', 'back', 'backRight', 'right', 'frontRight'];
const filenameDirection = { front: 'front', frontLeft: 'front_left', left: 'left', backLeft: 'back_left', back: 'back', backRight: 'back_right', right: 'right', frontRight: 'front_right' };
const counts = { front: [15, 9], frontLeft: [15, 11], left: [15, 10], backLeft: [15, 10], back: [16, 10], backRight: [15, 10], right: [15, 10], frontRight: [15, 11] };
const groups = {};
for (const facing of ['front', 'back']) groups[`${facing}_idle`] = { input, inputDirection: facing, motion: 'idle', count: 36 };
for (const facing of directions) for (const [motion, index] of [['walk', 0], ['sprint', 1]]) {
  // sprint2 is already named by its actual direction. The old sheet's extra swap no longer applies.
  groups[`${filenameDirection[facing]}_${motion}`] = { input: motion === 'sprint' ? sprintInput : input,
    inputDirection: filenameDirection[facing], motion,
    count: motion === 'sprint' ? sprintProvenance.directions[facing].frameCount : counts[facing][index] };
}

async function main() {
  fs.mkdirSync(output, { recursive: true });
  const audit = { version: 1, frameWidth: 128, frameHeight: 192, originalFrameCount: 0, originalBytes1x: 0, originalBytes2x: 0, atlasBytes1x: 0, atlasBytes2x: 0, sheets: {} };
  for (const [id, group] of Object.entries(groups)) {
    const columns = group.count > 16 ? 8 : 4;
    const rows = Math.ceil(group.count / columns);
    const frames = Array.from({ length: group.count }, (_, index) => `chr_player_chibi_${group.inputDirection}_${group.motion}_f${String(index).padStart(2, '0')}`);
    for (const density of [1, 2]) {
      const suffix = density === 1 ? '' : '@2x';
      const width = columns * 128 * density, height = rows * 192 * density;
      if (width > 2048 || height > 2048) throw new Error(`Oversize native texture: ${id}`);
      const packed = Buffer.alloc(width * height * 4);
      for (const [index, name] of frames.entries()) {
        const file = path.join(group.input, `${name}${suffix}.png`);
        const meta = await sharp(file).metadata();
        if (meta.width !== 128 * density || meta.height !== 192 * density) throw new Error(`Unexpected frame size: ${file}`);
        audit[`originalBytes${density}x`] += fs.statSync(file).size;
        const pixels = await sharp(file).ensureAlpha().raw().toBuffer();
        const left = (index % columns) * 128 * density, top = Math.floor(index / columns) * 192 * density;
        for (let row = 0; row < 192 * density; row++) pixels.copy(packed,
          ((top + row) * width + left) * 4, row * 128 * density * 4, (row + 1) * 128 * density * 4);
      }
      // Deliberately avoid @2x: the renderer chooses density from its actual displayed size.
      const out = path.join(output, `${id}${density === 1 ? '' : '_hd'}.png`);
      await sharp(packed, { raw: { width, height, channels: 4 } }).png({ compressionLevel: 9, palette: false }).toFile(out);
      audit[`atlasBytes${density}x`] += fs.statSync(out).size;
      // Decode every packed cell and verify it is byte-for-byte identical to the original RGBA.
      const atlas = await sharp(out).raw().toBuffer();
      for (const [index, name] of frames.entries()) {
        const original = await sharp(path.join(group.input, `${name}${suffix}.png`)).ensureAlpha().raw().toBuffer();
        const cell = await sharp(atlas, { raw: { width, height, channels: 4 } })
          .extract({ left: (index % columns) * 128 * density, top: Math.floor(index / columns) * 192 * density, width: 128 * density, height: 192 * density }).raw().toBuffer();
        if (!original.equals(cell)) throw new Error(`Changed pixels in ${name}${suffix}`);
      }
    }
    audit.originalFrameCount += group.count;
    audit.sheets[id] = { columns, rows, frameCount: group.count, sourceDirectory: path.basename(group.input), sourceFrames: frames };
  }
  fs.writeFileSync(path.join(output, 'atlas-audit.json'), `${JSON.stringify(audit, null, 2)}\n`);
  const lines = ["// Generated by scripts/prepare-player-atlases.cjs; exact original pixels and frame order.",
    "import type { AvatarAnimationManifest, AvatarAtlasSheet } from './avatarAnimation';", "",
    "const frontFallback = require('../../assets/images/game/characters/player/chibi-user-v3/chr_player_chibi_front_idle_f00.png');",
    "const backFallback = require('../../assets/images/game/characters/player/chibi-user-v3/chr_player_chibi_back_idle_f00.png');", "",
    "const sheets = {"];
  for (const [id, sheet] of Object.entries(audit.sheets)) lines.push(`  ${id}: { id: '${id}', source: require('../../assets/images/game/characters/player/chibi-atlas-v1/${id}.png'), highResolutionSource: require('../../assets/images/game/characters/player/chibi-atlas-v1/${id}_hd.png'), columns: ${sheet.columns}, rows: ${sheet.rows}, frameCount: ${sheet.frameCount}, frameWidth: 128, frameHeight: 192 },`);
  lines.push('} satisfies Record<string, AvatarAtlasSheet>;', '', 'export const chibiPlayerAvatar: AvatarAnimationManifest = {');
  for (const facing of directions) {
    const idle = facing.startsWith('back') ? 'back' : 'front';
    lines.push(`  ${facing}: { idle: [${idle}Fallback], walk: [${idle}Fallback], sprint: [${idle}Fallback] },`);
  }
  lines.push('  atlases: {');
  for (const facing of directions) {
    const prefix = filenameDirection[facing], idle = facing.startsWith('back') ? 'back' : 'front';
    lines.push(`    ${facing}: { idle: sheets.${idle}_idle, walk: sheets.${prefix}_walk, sprint: sheets.${prefix}_sprint },`);
  }
  lines.push('  },', '};', '');
  fs.writeFileSync(path.join(root, 'src/game/chibiPlayerAvatar.ts'), lines.join('\n'));
  console.log(JSON.stringify({ frames: audit.originalFrameCount, sheets: Object.keys(audit.sheets).length,
    originalBytes1x: audit.originalBytes1x, originalBytes2x: audit.originalBytes2x,
    atlasBytes1x: audit.atlasBytes1x, atlasBytes2x: audit.atlasBytes2x,
    largestTexturePixels2x: Math.max(...Object.values(audit.sheets).map(s => s.columns * 256 * s.rows * 384)),
    verifiedOriginalPixels: true }, null, 2));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
